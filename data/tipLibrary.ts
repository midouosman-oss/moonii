export function getTipsForPhase(phase: Phase, region?: string): Tip[] {
  const normalized = (region ?? "").toLowerCase();
  const targetRegion = normalized.includes("india")
    ? "India"
    : normalized.includes("thailand") || normalized.includes("bangkok")
      ? "Thailand"
      : null;

  const phaseTips = TIP_LIBRARY.filter(
    (tip) =>
      tip.phase === phase &&
      (!targetRegion || tip.regions.includes("Global") || tip.regions.includes(targetRegion)),
  );

  // Show one rotating suggestion per pillar rather than flooding Daily Care
  // with every entry assigned to the current phase.
  const now = new Date();
  const dayOfYear = Math.floor(
    (Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) -
      Date.UTC(now.getFullYear(), 0, 0)) / 86400000,
  );

  return (["Nourishment", "Movement", "Mind"] as Pillar[]).flatMap((pillar) => {
    const options = phaseTips.filter((tip) => tip.pillar === pillar);
    if (!options.length) return [];
    return [options[dayOfYear % options.length]];
  });
}